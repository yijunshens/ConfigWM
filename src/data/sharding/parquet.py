logger = logging.getLogger(__name__)


def _scan_parquet_row_groups(path: Path) -> list[tuple[int, int]]:
    """Return [(row_group_index, num_rows), ...] for a parquet file."""
    import pyarrow.parquet as pq

    pf = pq.ParquetFile(path)
    return [
        (rg_idx, pf.metadata.row_group(rg_idx).num_rows)
        for rg_idx in range(pf.metadata.num_row_groups)
    ]


def _default_parquet_meta_dir(files: Sequence[Path]) -> Path:
    common = Path(os.path.commonpath([str(f.parent) for f in files]))
    return common / ".parquet_meta"


def ensure_parquet_meta(
    paths: Sequence[str | Path],
    *,
    meta_dir: str | Path | None = None,
    progress_callback: Callable[[dict[str, Any]], None] | None = None,
) -> tuple[list[Path], list[list[tuple[int, int]]]]:
    """Ensure per-file parquet row-group metadata sidecars exist.

    Each sidecar is a JSON file: ``[[row_group_index, num_rows], ...]``.

    Returns:
        (files, row_groups_per_file) — parallel lists.
    """
    files = _normalize_paths(paths)

    if meta_dir is not None:
        resolved_meta_dir = Path(meta_dir).expanduser().resolve()
    else:
        preferred = _default_parquet_meta_dir(files)
        try:
            preferred.mkdir(parents=True, exist_ok=True)
            resolved_meta_dir = preferred
        except OSError:
            from .common import DEFAULT_MANIFEST_CACHE_ROOT

            if DEFAULT_MANIFEST_CACHE_ROOT is None:
                raise PermissionError(
                    f"Cannot create meta dir at {preferred} (read-only) "
                    "and no manifest_cache_root is configured as fallback."
                ) from None
            label = preferred.parent.name or "dataset"
            resolved_meta_dir = (
                DEFAULT_MANIFEST_CACHE_ROOT / f"{label}.parquet_meta"
            )
            logger.info(
                "Data dir is read-only, falling back to %s", resolved_meta_dir
            )

    resolved_meta_dir.mkdir(parents=True, exist_ok=True)
    with contextlib.suppress(OSError):
        os.chmod(resolved_meta_dir, 0o775)

    readme_path = resolved_meta_dir / "README"
    if not readme_path.exists():
        with contextlib.suppress(OSError):
            readme_path.write_text(
                "Row-group metadata sidecars for the Parquet files in the parent directory.\n"
                "\n"
                "Format\n"
                "  NNNNNN.rowgroups.json  JSON array of [row_group_index, num_rows] pairs.\n"
                "\n"
                "File naming: NNNNNN is a zero-padded index into the alphabetically\n"
                "sorted list of Parquet files in the parent directory.\n"
                "\n"
                "Generated by: python -m src.data.manifest.build\n"
                "Config-independent. Shared across all users and training configs.\n"
                "Do not delete unless the Parquet files themselves have changed.\n"
            )

    def emit_progress(event: dict[str, Any]) -> None:
        if progress_callback is not None:
            progress_callback(event)

    all_row_groups: list[list[tuple[int, int]]] = []

    for file_index, path in enumerate(files):
        started_at = perf_counter()
        meta_path = resolved_meta_dir / f"{file_index:06d}.rowgroups.json"

        if meta_path.exists():
            row_groups = [
                tuple(pair) for pair in json.loads(meta_path.read_text())
            ]
        else:
            row_groups = _scan_parquet_row_groups(path)
            payload = json.dumps(row_groups, separators=(",", ":")).encode()
            _atomic_write_bytes(meta_path, payload)

        total_rows = sum(rg[1] for rg in row_groups)
        all_row_groups.append(row_groups)

        emit_progress(
            {
                "event": "file_scanned",
                "file_index": file_index + 1,
                "num_files": len(files),
                "path": str(path),
                "record_count": total_rows,
                "running_total_records": sum(
                    sum(rg[1] for rg in rgs) for rgs in all_row_groups
                ),
                "elapsed_sec": perf_counter() - started_at,
            }
        )

    total = sum(sum(rg[1] for rg in rgs) for rgs in all_row_groups)
    logger.info(
        "Parquet meta ready: files=%d records=%s meta_dir=%s",
        len(files),
        f"{total:,}",
        resolved_meta_dir,
    )
    return files, all_row_groups


def _build_parquet_manifest_dict(
    parquet_files: Sequence[str | Path],
    *,
    samples_per_chunk: int = DEFAULT_PARQUET_SAMPLES_PER_CHUNK,
    meta_dir: str | Path | None = None,
    cache_root: str | Path | None = None,  # Deprecated, ignored.
    progress_callback: Callable[[dict[str, Any]], None] | None = None,
) -> dict[str, Any]:
    """Build a parquet manifest from pre-scanned row-group metadata."""
    if samples_per_chunk < 1:
        raise ValueError("samples_per_chunk must be >= 1")

    files, all_row_groups = ensure_parquet_meta(
        parquet_files,
        meta_dir=meta_dir,
        progress_callback=progress_callback,
    )

    chunk_file_indices: list[int] = []
    chunk_row_group_indices: list[int] = []
    chunk_row_starts: list[int] = []
    chunk_num_rows: list[int] = []
    chunk_start_record_indices: list[int] = []
    total_records = 0

    for file_index, row_groups in enumerate(all_row_groups):
        for row_group_index, row_group_rows in row_groups:
            row_start = 0
            while row_start < row_group_rows:
                num_rows = min(samples_per_chunk, row_group_rows - row_start)
                chunk_file_indices.append(file_index)
                chunk_row_group_indices.append(row_group_index)
                chunk_row_starts.append(row_start)
                chunk_num_rows.append(num_rows)
                chunk_start_record_indices.append(total_records)
                total_records += num_rows
                row_start += num_rows

    manifest = {
        "kind": "parquet",
        "files": [str(path) for path in files],
        "chunk_file_indices": chunk_file_indices,
        "chunk_row_group_indices": chunk_row_group_indices,
        "chunk_row_starts": chunk_row_starts,
        "chunk_num_rows": chunk_num_rows,
        "chunk_start_record_indices": chunk_start_record_indices,
        "total_records": total_records,
        "manifest_version": MANIFEST_VERSION,
    }

    logger.info(
        "Parquet manifest ready: files=%d records=%s chunks=%d",
        len(files),
        f"{total_records:,}",
        len(chunk_file_indices),
    )
    return manifest


class ParquetShardSource(ManifestBackedShardSource):
    """Typed parquet manifest-backed sharding source."""

    def __init__(self, raw_manifest: Mapping[str, Any]) -> None:
        super().__init__(
            kind="parquet",
            raw_manifest=raw_manifest,
            total_items_key="total_records",
        )

    @classmethod
    def from_manifest(cls, manifest: Mapping[str, Any]) -> ParquetShardSource:
        return cls(manifest)

    @classmethod
    def from_files(
        cls,
        parquet_files: Sequence[str | Path],
        *,
        samples_per_chunk: int = DEFAULT_PARQUET_SAMPLES_PER_CHUNK,
        meta_dir: str | Path | None = None,
        cache_root: str | Path | None = None,  # Deprecated, ignored.
        progress_callback: Callable[[dict[str, Any]], None] | None = None,
    ) -> ParquetShardSource:
        return cls(
            _build_parquet_manifest_dict(
                parquet_files,
                samples_per_chunk=samples_per_chunk,
                meta_dir=meta_dir,
                progress_callback=progress_callback,
            )
        )

    @classmethod
    def from_data_dir(
        cls,
        data_dir: str | Path,
        *,
        split: str = "train",
        samples_per_chunk: int = DEFAULT_PARQUET_SAMPLES_PER_CHUNK,
        meta_dir: str | Path | None = None,
        cache_root: str | Path | None = None,  # Deprecated, ignored.
        progress_callback: Callable[[dict[str, Any]], None] | None = None,
    ) -> ParquetShardSource:
        return cls.from_files(
            resolve_parquet_files(data_dir, split),
            samples_per_chunk=samples_per_chunk,
            meta_dir=meta_dir,
            progress_callback=progress_callback,
        )

    def iter_chunks(self) -> Iterator[ChunkInfo]:
        for chunk_index, file_index in enumerate(
            self.raw_manifest["chunk_file_indices"]
        ):
            yield ChunkInfo(
                file_index=int(file_index),
                file_path=self.files[int(file_index)],
                start_record_index=int(
                    self.raw_manifest["chunk_start_record_indices"][chunk_index]
                ),
                num_items=int(self.raw_manifest["chunk_num_rows"][chunk_index]),
            )

    def iter_rows(
        self,
        *,
        columns: Sequence[str] | None = None,
        seed: int = 0,
        epoch: int = 0,
        info: ShardInfo | None = None,
        shuffle: bool = True,
        shuffle_buffer_size: int = DEFAULT_STREAM_SHUFFLE_BUFFER,
    ) -> Iterator[tuple[int, Path, dict[str, Any]]]:
        import pyarrow.parquet as pq

        info = info or get_shard_info()
        physical_manifest = dict(self.raw_manifest)
        physical_chunk_count = len(physical_manifest["chunk_file_indices"])
        manifest = _logical_parquet_manifest(physical_manifest, info=info)
        if len(manifest["chunk_file_indices"]) > physical_chunk_count:
            _warn_parquet_logical_split_once(
                manifest=physical_manifest,
                info=info,
                logical_chunk_count=len(manifest["chunk_file_indices"]),
            )

        owned_indices = _owned_chunk_indices(
            len(manifest["chunk_file_indices"]),
            seed=seed,
            epoch=epoch,
            info=info,
            shuffle=shuffle,
        )
        parquet_cache: dict[Path, pq.ParquetFile] = {}

        def iter_owned_rows() -> Iterator[tuple[int, Path, dict[str, Any]]]:
            for chunk_index in owned_indices:
                file_path = self.files[
                    manifest["chunk_file_indices"][chunk_index]
                ]
                parquet_file = parquet_cache.get(file_path)
                if parquet_file is None:
                    parquet_file = pq.ParquetFile(file_path)
                    parquet_cache[file_path] = parquet_file

                row_group_index = manifest["chunk_row_group_indices"][
                    chunk_index
                ]
                row_start = manifest["chunk_row_starts"][chunk_index]
                num_rows = manifest["chunk_num_rows"][chunk_index]
                start_record_index = manifest["chunk_start_record_indices"][
                    chunk_index
                ]

                table = parquet_file.read_row_group(
                    row_group_index, columns=columns
                )
                if row_start != 0 or num_rows != table.num_rows:
                    table = table.slice(row_start, num_rows)

                table_columns = {
                    name: table.column(name) for name in table.schema.names
                }
                for row_offset in range(table.num_rows):
                    yield (
                        start_record_index + row_offset,
                        file_path,
                        {
                            name: column[row_offset].as_py()
                            for name, column in table_columns.items()
                        },
                    )

        yield from _iter_shuffle_buffer(
            iter_owned_rows(),
            shuffle=shuffle,
            shuffle_buffer_size=shuffle_buffer_size,
            seed=seed,
            epoch=epoch,
            info=info,
        )


def _logical_parquet_manifest(
    manifest: Mapping[str, Any],
    *,
    info: ShardInfo,
) -> dict[str, Any]:
    logical_plan = _plan_logical_subchunks(
        physical_chunk_sizes=manifest["chunk_num_rows"],
        total_items=int(manifest["total_records"]),
        total_slots=info.total_slots,
    )
    if logical_plan is None:
        return dict(manifest)

    chunk_file_indices: list[int] = []
    chunk_row_group_indices: list[int] = []
    chunk_row_starts: list[int] = []
    chunk_num_rows: list[int] = []
    chunk_start_record_indices: list[int] = []

    for chunk_index, file_index in enumerate(manifest["chunk_file_indices"]):
        row_group_index = manifest["chunk_row_group_indices"][chunk_index]
        row_start = manifest["chunk_row_starts"][chunk_index]
        record_index = manifest["chunk_start_record_indices"][chunk_index]
        for row_offset, logical_rows in logical_plan[chunk_index]:
            chunk_file_indices.append(file_index)
            chunk_row_group_indices.append(row_group_index)
            chunk_row_starts.append(row_start + row_offset)
            chunk_num_rows.append(logical_rows)
            chunk_start_record_indices.append(record_index + row_offset)

    logical_manifest = dict(manifest)
    logical_manifest["chunk_file_indices"] = chunk_file_indices
    logical_manifest["chunk_row_group_indices"] = chunk_row_group_indices
    logical_manifest["chunk_row_starts"] = chunk_row_starts
    logical_manifest["chunk_num_rows"] = chunk_num_rows
    logical_manifest["chunk_start_record_indices"] = chunk_start_record_indices
    return logical_manifest


def resolve_parquet_files(
    data_dir: str | Path,
    split: str = "train",
) -> list[Path]:
    """Resolve local parquet files for the requested split."""
    base_dir = Path(data_dir)
    search_roots = [base_dir / "data", base_dir]

    parquet_files: list[Path] = []
    for root in search_roots:
        if not root.exists():
            continue

        direct_file = root / f"{split}.parquet"
        if direct_file.exists():
            parquet_files = [direct_file]
            break

        split_prefixed = sorted(root.glob(f"{split}-*.parquet"))
        if split_prefixed:
            parquet_files = split_prefixed
            break

        split_dir = root / split
        if split_dir.exists():
            nested_files = sorted(split_dir.glob("*.parquet"))
            if nested_files:
                parquet_files = nested_files
                break

        if split == "train":
            any_parquet = sorted(root.glob("*.parquet"))
            if any_parquet:
                parquet_files = any_parquet
                break

    if not parquet_files:
        raise ValueError(
            f"No parquet files found for split '{split}' in {base_dir}"
        )

    return parquet_files


def iter_parquet_chunks(
    manifest_or_paths: ParquetShardSource
    | Mapping[str, Any]
    | Sequence[str | Path],
    *,
    columns: Sequence[str] | None = None,
    seed: int = 0,
    epoch: int = 0,
    info: ShardInfo | None = None,
    samples_per_chunk: int = DEFAULT_PARQUET_SAMPLES_PER_CHUNK,
    meta_dir: str | Path | None = None,
    shuffle: bool = True,
    shuffle_buffer_size: int = DEFAULT_STREAM_SHUFFLE_BUFFER,
) -> Iterator[tuple[int, Path, dict[str, Any]]]:
    """Iterate owned parquet chunks using manifest metadata."""
    if isinstance(manifest_or_paths, ParquetShardSource):
        source = manifest_or_paths
    elif isinstance(manifest_or_paths, Mapping):
        source = ParquetShardSource.from_manifest(manifest_or_paths)
    else:
        source = ParquetShardSource.from_files(
            manifest_or_paths,
            samples_per_chunk=samples_per_chunk,
            meta_dir=meta_dir,
        )
    yield from source.iter_rows(
        columns=columns,
        seed=seed,
        epoch=epoch,
        info=info,
        shuffle=shuffle,
        shuffle_buffer_size=shuffle_buffer_size,
    )
